package interfaces

import (
	"context"
	"io"
	"time"

	"github.com/sanjeev0303/object-storage-platform/internal/model"
)

// StorageProvider is one connection's storage, whatever the provider:
// everything uploads, processing, delivery and lifecycle ask of it. An
// adapter implements each operation the way its provider does it (S3
// multipart, GCS composite parts, Azure blocks) and reports what it
// cannot do through ProviderCapabilities instead of pretending.
type StorageProvider interface {
	MultipartStorage
	ObjectDelivery
	LifecycleStorage
	// WriteObject stores size bytes read from body, streaming with bounded
	// memory: the receiving half of a transfer between connections.
	WriteObject(ctx context.Context, bucket, objectKey string, body io.Reader, size int64, contentType string) (ObjectMetadata, error)
	// ProviderCapabilities finds what the provider and bucket can do.
	ProviderCapabilities(ctx context.Context, bucket string) (model.ProviderCapabilities, error)
}

// StoragePlace is where one connection keeps an organization's bytes:
// uploads land under the staging prefix, published versions under the
// ready prefix. Keys are always generated by the platform.
type StoragePlace struct {
	ConnectionID  string
	StagingBucket string
	StagingPrefix string
	ReadyBucket   string
	ReadyPrefix   string
}

// StagingKey is where an upload's bytes land.
func (p StoragePlace) StagingKey(tenantID, uploadID string) string {
	return p.StagingPrefix + "/" + tenantID + "/" + uploadID
}

// StorageLocation is a connection's place with the client that reaches it.
type StorageLocation struct {
	StoragePlace
	Provider     model.StorageProviderType
	Storage      StorageProvider
	Capabilities model.ProviderCapabilities
}

// StorageRouter resolves the connection a record is bound to. It never
// falls back to another connection: a record's bytes are reached through
// the connection that wrote them or not at all.
type StorageRouter interface {
	// Locate returns a connection that still holds work (active or
	// disabled) for the tenant: the platform connection, or one of the
	// tenant's own.
	Locate(ctx context.Context, tenantID, connectionID string) (StorageLocation, error)
}

// StorageChoice is where a new upload goes: the connection that will hold
// its published bytes, and the connection its upload lands on (the same,
// unless the connection stages uploads on the platform).
type StorageChoice struct {
	Final   StorageLocation
	Staging StorageLocation
}

// StorageChooser picks the connection for new work: the one asked for,
// the dataset's, or the organization's default.
type StorageChooser interface {
	ChooseForUpload(ctx context.Context, p model.Principal, requestedConnectionID, dataset string) (StorageChoice, error)
}

// StorageConnectionRepository stores connections and their sealed
// credentials.
type StorageConnectionRepository interface {
	CreateConnection(ctx context.Context, c model.StorageConnection, sealed SealedCredential) (model.StorageConnection, error)
	GetConnection(ctx context.Context, tenantID, connectionID string) (model.StorageConnection, error)
	ListConnections(ctx context.Context, tenantID string) ([]model.StorageConnection, error)
	UpdateConnection(ctx context.Context, tenantID, connectionID string, revision int64, change ConnectionChange) (model.StorageConnection, error)
	RotateCredential(ctx context.Context, tenantID, connectionID string, revision int64, sealed SealedCredential, actor string, at time.Time) (model.StorageConnection, error)
	// Credential returns the sealed credential of exactly this version.
	Credential(ctx context.Context, tenantID, connectionID string, version int) (SealedCredential, error)
	RecordTest(ctx context.Context, tenantID, connectionID string, result ConnectionTestRecord) (model.StorageConnection, error)
	SetStatus(ctx context.Context, tenantID, connectionID string, from []model.ConnectionStatus, to model.ConnectionStatus, actor string, at time.Time) (model.StorageConnection, error)
	// Disable moves an active or pending connection to DISABLED unless it
	// is the organization's default (model.ErrConnectionInUse), checked
	// and changed together so a concurrent SetDefault cannot leave a
	// disabled default.
	Disable(ctx context.Context, tenantID, connectionID, actor string, at time.Time) (model.StorageConnection, error)
	// Dependents counts what still depends on the connection: unfinished
	// uploads, live assets, datasets choosing it, and whether it is the
	// default.
	Dependents(ctx context.Context, tenantID, connectionID string) (ConnectionDependents, error)
	// HeldObject is the key of one published object the connection holds
	// in its bucket, "" when it holds none.
	HeldObject(ctx context.Context, tenantID, connectionID string) (string, error)
	// Delete tombstones the connection and erases its credentials, if
	// nothing depends on it, in one transaction.
	Delete(ctx context.Context, tenantID, connectionID, actor string, at time.Time) (model.StorageConnection, error)
	DefaultConnection(ctx context.Context, tenantID string) (string, error)
	SetDefault(ctx context.Context, tenantID, connectionID string) error
	// DatasetConnection is the connection a dataset (by name) chose; ""
	// when it chose none.
	DatasetConnection(ctx context.Context, tenantID, dataset string) (string, error)
}

// SealedCredential is a credential as stored: ciphertext only.
type SealedCredential struct {
	Version    int
	KeyVersion int
	Nonce      []byte
	Ciphertext []byte
}

// ConnectionChange changes a connection's non-secret settings; nil leaves
// a field as it is. The status is left alone: a change of where a
// connection that holds work points is tested before it is made.
type ConnectionChange struct {
	Name           *string
	Region         *string
	Endpoint       *string
	ForcePathStyle *bool
	StagingMode    *model.StagingMode
	ChecksumMode   *string
	// ExpectedOwner: "" unpins the owner.
	ExpectedOwner *string
	// EncryptionKey: "" returns to the bucket's default encryption.
	EncryptionKey *string
	Actor         string
	At            time.Time
}

// PlacementGuard says whether a dataset's data may be stored on a
// connection ("" is the organization's default).
type PlacementGuard interface {
	CheckPlacement(ctx context.Context, p model.Principal, rules model.PlacementRules, connectionID string) error
	CheckDatasetPlacement(ctx context.Context, p model.Principal, dataset, connectionID string) error
}

// PostureInspector is a provider that can describe its bucket's security
// settings (docs/storage-posture.md).
type PostureInspector interface {
	Posture(ctx context.Context, bucket string, opts model.PostureOptions) (model.PostureFacts, error)
}

// SSECProber is a provider that can try a write encrypted with a
// customer-provided key, to learn whether the bucket refuses one.
type SSECProber interface {
	ProbeSSEC(ctx context.Context, bucket, key string) (accepted bool, err error)
}

// ConnectionTestRecord is what a connection test found, sanitized.
type ConnectionTestRecord struct {
	OK            bool
	ErrorCategory string
	Capabilities  *model.ProviderCapabilities
	At            time.Time
}

// ConnectionDependents is what blocks deleting a connection.
type ConnectionDependents struct {
	ActiveUploads int64
	LiveAssets    int64
	Datasets      int64
	IsDefault     bool
}

// Any tells whether anything depends on the connection.
func (d ConnectionDependents) Any() bool {
	return d.ActiveUploads > 0 || d.LiveAssets > 0 || d.Datasets > 0 || d.IsDefault
}

// ConnectionLister lists the tenants' connections that may still hold
// data (active or disabled), for workers that sweep every connection.
type ConnectionLister interface {
	// ConnectionsHoldingWork lists them for one tenant, or for all when
	// tenantID is "". The platform connection is not included.
	ConnectionsHoldingWork(ctx context.Context, tenantID string) ([]model.StorageConnection, error)
}
