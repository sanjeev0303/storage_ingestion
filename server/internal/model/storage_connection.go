// Storage connections (Phase 11): where an organization's bytes live.
// Every organization starts on the platform-managed connection, the
// deployment's own buckets. It may add connections to its own storage
// (bring your own storage) and choose one as its default. Every upload
// and object version records the connection it was written to, and is
// served, processed and deleted through that connection only, whatever
// the default is later.

var (
	ErrConnectionNotFound   = errors.New("storage connection not found")
	ErrConnectionNotActive  = errors.New("the storage connection is not active")
	ErrConnectionInUse      = errors.New("the storage connection still holds uploads or objects")
	ErrConnectionExists     = errors.New("a storage connection with this name exists")
	ErrInvalidConnection    = errors.New("invalid storage connection")
	ErrUnsupportedProvider  = errors.New("the storage provider does not support this")
	ErrEndpointRejected     = errors.New("the storage endpoint is not allowed")
	ErrCredentialMissing    = errors.New("the storage connection has no credentials")
	ErrStorageNotConfigured = errors.New("customer-managed storage is not enabled")
)

// PlatformConnectionID is the platform-managed connection's ID, shared by
// every organization. Records written before connections existed belong
// to it.
const PlatformConnectionID = "platform"

// IsPlatformConnection tells whether a binding is the platform's. Every
// stored record names its binding (the columns are NOT NULL, and records
// older than connections were bound to "platform" by migration), so an
// empty one is a lost binding, never the platform's: resolving it fails.
func IsPlatformConnection(id string) bool { return id == PlatformConnectionID }

// StorageProviderType names a storage provider.
type StorageProviderType string

const (
	ProviderPlatform     StorageProviderType = "PLATFORM_MANAGED"
	ProviderAWSS3        StorageProviderType = "AWS_S3"
	ProviderS3Compatible StorageProviderType = "S3_COMPATIBLE"
	ProviderR2           StorageProviderType = "CLOUDFLARE_R2"
	ProviderGCS          StorageProviderType = "GOOGLE_CLOUD_STORAGE"
	ProviderAzureBlob    StorageProviderType = "AZURE_BLOB"
)

// CustomerProviders are the providers an organization can connect.
var CustomerProviders = []StorageProviderType{ProviderAWSS3, ProviderS3Compatible, ProviderR2, ProviderGCS, ProviderAzureBlob}

// S3Family tells whether the provider speaks the S3 API.
func (p StorageProviderType) S3Family() bool {
	return p == ProviderPlatform || p == ProviderAWSS3 || p == ProviderS3Compatible || p == ProviderR2
}

// ConnectionStatus is a connection's state.
type ConnectionStatus string

const (
	// ConnectionPending: created, not yet tested successfully. No new
	// work goes to it.
	ConnectionPending ConnectionStatus = "PENDING"
	// ConnectionActive: tested; new uploads may use it.
	ConnectionActive ConnectionStatus = "ACTIVE"
	// ConnectionDisabled: no new work; what it already holds is still
	// read, processed and deleted through it.
	ConnectionDisabled ConnectionStatus = "DISABLED"
	// ConnectionDeleted is a tombstone: nothing depended on it any more,
	// and its credentials are erased.
	ConnectionDeleted ConnectionStatus = "DELETED"
)

// StorageAuthMethod is how the platform authenticates to a connection.
type StorageAuthMethod string

const (
	// AuthPlatform: the deployment's own configuration (the platform
	// connection only).
	AuthPlatform StorageAuthMethod = "PLATFORM"
	// AuthAccessKey: an access key ID and secret (and, for AWS, an
	// optional session token).
	AuthAccessKey StorageAuthMethod = "ACCESS_KEY"
	// AuthAssumeRole: the platform's own AWS identity assumes a role in the
	// customer's account. The external ID is generated by the platform,
	// so one organization cannot use another's role.
	AuthAssumeRole StorageAuthMethod = "ASSUME_ROLE"
	// AuthServiceAccountKey: a Google service account key (JSON).
	AuthServiceAccountKey StorageAuthMethod = "SERVICE_ACCOUNT_KEY"
	// AuthAccountKey: an Azure storage account's shared key.
	AuthAccountKey StorageAuthMethod = "ACCOUNT_KEY"
	// AuthSASToken: an Azure shared access signature scoped to the
	// container. It cannot sign client URLs (that would hand the token
	// itself out), so such a connection stages uploads on the platform.
	AuthSASToken StorageAuthMethod = "SAS_TOKEN"
)

// authMethods are the methods each provider accepts.
var authMethods = map[StorageProviderType][]StorageAuthMethod{
	ProviderPlatform:     {AuthPlatform},
	ProviderAWSS3:        {AuthAccessKey, AuthAssumeRole},
	ProviderS3Compatible: {AuthAccessKey},
	ProviderR2:           {AuthAccessKey},
	ProviderGCS:          {AuthServiceAccountKey},
	ProviderAzureBlob:    {AuthAccountKey, AuthSASToken},
}

// AuthMethods lists the methods a provider accepts.
func AuthMethods(p StorageProviderType) []StorageAuthMethod { return slices.Clone(authMethods[p]) }

// SecretFields are the credential fields a method needs.
func (m StorageAuthMethod) SecretFields() []string {
	switch m {
	case AuthAccessKey:
		return []string{"access_key_id", "secret_access_key"}
	case AuthServiceAccountKey:
		return []string{"service_account_json"}
	case AuthAccountKey:
		return []string{"account_key"}
	case AuthSASToken:
		return []string{"sas_token"}
	}
	return nil
}

// StagingMode says where uploads land before they are verified.
type StagingMode string

const (
	// StagingInPlace: uploads land under the connection's own staging
	// prefix and are promoted with a copy inside the provider.
	StagingInPlace StagingMode = "CONNECTION"
	// StagingPlatform: uploads land in the platform's quarantine; only
	// verified, scanned bytes are streamed to the connection's ready
	// prefix. Unverified content never reaches the customer's bucket.
	StagingPlatform StagingMode = "PLATFORM"
)

// StorageConnection is one place an organization's bytes can live.
// It holds no secret: credentials are stored encrypted beside it.
type StorageConnection struct {
	ID         string
	TenantID   string
	Name       string
	Provider   StorageProviderType
	Status     ConnectionStatus
	AuthMethod StorageAuthMethod
	// Where: Bucket is the S3 or GCS bucket, or the Azure container.
	Bucket string
	Region string
	// Endpoint is the S3-compatible service URL (empty for AWS's own).
	Endpoint string
	// AccountID is the Cloudflare account, the Azure storage account, or
	// the Google project.
	AccountID      string
	ForcePathStyle bool
	// RoleARN and ExternalID are for AWS ASSUME_ROLE.
	RoleARN       string
	ExternalID    string
	StagingPrefix string
	ReadyPrefix   string
	StagingMode   StagingMode

	// Credentials: their version (0: none stored), the encryption key
	// that sealed them, and when they last changed.
	CredentialVersion    int
	CredentialKeyVersion int
	CredentialRotatedAt  *time.Time

	Capabilities          *ProviderCapabilities
	CapabilitiesCheckedAt *time.Time
	LastTestedAt          *time.Time
	LastTestOKAt          *time.Time
	// LastErrorCategory is a sanitized category, never a provider message.
	LastErrorCategory string

	// ChecksumMode is AUTO, WHEN_SUPPORTED or WHEN_REQUIRED; ExpectedOwner
	// the AWS account or Google project number the bucket must belong to
	// ("" when not pinned). See docs/storage-posture.md.
	ChecksumMode  string
	ExpectedOwner string
	// EncryptionKey is the customer-managed key every write is encrypted
	// with: a KMS key on AWS, a Cloud KMS key on GCS, an encryption scope
	// on Azure ("" uses the bucket's default). See docs/residency.md.
	EncryptionKey string
	// A second credential, tested and waiting to be promoted, and the one a
	// promotion replaced, kept for a rollback until PreviousUntil.
	StagedCredentialVersion   int
	StagedAt                  *time.Time
	StagedBy                  string
	PreviousCredentialVersion int
	PreviousUntil             *time.Time

	Revision   int64
	CreatedBy  string
	UpdatedBy  string
	CreatedAt  time.Time
	UpdatedAt  time.Time
	DisabledAt *time.Time
	DeletedAt  *time.Time
}

// CredentialAAD is the associated data a credential version is sealed
// with. It binds the ciphertext to its tenant, connection, provider and
// version: a ciphertext copied to another row, or replayed as another
// version, does not open.
func (c StorageConnection) CredentialAAD(version int) []byte {
	return fmt.Appendf(nil, "storage-credential/v1|%s|%s|%s|%d", c.TenantID, c.ID, c.Provider, version)
}

// HasCredential tells whether credentials are stored.
func (c StorageConnection) HasCredential() bool { return c.CredentialVersion > 0 }

// AcceptsNewWork tells whether new uploads may go to the connection.
func (c StorageConnection) AcceptsNewWork() bool {
	return c.ID == PlatformConnectionID || c.Status == ConnectionActive
}

// HoldsWork tells whether existing data may still be reached through it.
func (c StorageConnection) HoldsWork() bool {
	return c.ID == PlatformConnectionID || c.Status == ConnectionActive || c.Status == ConnectionDisabled
}

// ProviderCapabilities are what a connection's provider can do for the
// platform, as found when it was last tested. Every listed operation was
// implemented for the provider; nothing is advertised by assumption.
type ProviderCapabilities struct {
	// Client uploads straight to storage with a signed URL.
	PresignedUpload bool `json:"presigned_upload"`
	// MaxSingleUploadBytes caps one signed upload.
	MaxSingleUploadBytes int64 `json:"max_single_upload_bytes"`
	// Large uploads in independently retried parts: S3 multipart, GCS
	// parallel composite parts, or Azure blocks.
	Multipart     bool   `json:"multipart"`
	MultipartKind string `json:"multipart_kind,omitempty"`
	MaxParts      int    `json:"max_parts,omitempty"`
	MinPartBytes  int64  `json:"min_part_bytes,omitempty"`
	// PartValidator is what a part's "ETag" is: CONTENT (derived from the
	// bytes) or BLOCK_ID (Azure blocks have no content validator).
	PartValidator         string `json:"part_validator,omitempty"`
	ListIncompleteUploads bool   `json:"list_incomplete_uploads"`
	ServerSideCopy        bool   `json:"server_side_copy"`
	RangeReads            bool   `json:"range_reads"`
	ConditionalReads      bool   `json:"conditional_reads"`
	PresignedDownload     bool   `json:"presigned_download"`
	ListObjects           bool   `json:"list_objects"`
	// ProviderVersioning: the bucket keeps versions; VersionIDKind says
	// what a version ID is (S3 version ID, GCS generation, Azure version).
	ProviderVersioning bool   `json:"provider_versioning"`
	VersioningStatus   string `json:"versioning_status,omitempty"`
	VersionIDKind      string `json:"version_id_kind,omitempty"`
	// ChecksumAlgorithms the provider records itself. The platform always
	// verifies SHA-256 by reading the bytes.
	ChecksumAlgorithms []string `json:"checksum_algorithms"`
}

// StorageSecrets are a connection's credentials, decrypted. They exist
// only while a provider client is built: never log, return or store
// them; every way of printing them prints a placeholder.
type StorageSecrets struct {
	AccessKeyID        string
	SecretAccessKey    string
	SessionToken       string
	ServiceAccountJSON string
	AccountKey         string
	SASToken           string
}

func (StorageSecrets) String() string               { return "[redacted credentials]" }
func (StorageSecrets) GoString() string             { return "[redacted credentials]" }
func (StorageSecrets) LogValue() slog.Value         { return slog.StringValue("[redacted credentials]") }
func (StorageSecrets) MarshalText() ([]byte, error) { return []byte("[redacted credentials]"), nil }

// ValidateFor checks the secrets hold exactly what method needs.
func (s StorageSecrets) ValidateFor(method StorageAuthMethod) error {
	have := map[string]bool{
		"access_key_id": s.AccessKeyID != "", "secret_access_key": s.SecretAccessKey != "", "session_token": s.SessionToken != "",
		"service_account_json": s.ServiceAccountJSON != "", "account_key": s.AccountKey != "", "sas_token": s.SASToken != "",
	}
	allowed := method.SecretFields()
	if method == AuthAccessKey {
		allowed = append(allowed, "session_token")
	}
	for _, need := range method.SecretFields() {
		if !have[need] {
			return fmt.Errorf("%w: %s needs %s", ErrInvalidConnection, method, need)
		}
	}
	for field, present := range have {
		if present && !slices.Contains(allowed, field) {
			return fmt.Errorf("%w: %s does not take %s", ErrInvalidConnection, method, field)
		}
	}
	for _, v := range []string{s.AccessKeyID, s.SecretAccessKey, s.SessionToken, s.AccountKey, s.SASToken} {
		if len(v) > 4096 || strings.ContainsAny(v, "\r\n\x00") {
			return fmt.Errorf("%w: a credential field is malformed", ErrInvalidConnection)
		}
	}
	if len(s.ServiceAccountJSON) > 16*1024 {
		return fmt.Errorf("%w: the service account key is too large", ErrInvalidConnection)
	}
	return nil
}

var (
	bucketPattern  = regexp.MustCompile(`^[a-z0-9][a-z0-9.\-_]{1,220}[a-z0-9]$`)
	prefixPattern  = regexp.MustCompile(`^[a-z0-9][a-z0-9\-_]{0,62}$`)
	regionPattern  = regexp.MustCompile(`^[a-z0-9\-]{0,64}$`)
	accountPattern = regexp.MustCompile(`^[A-Za-z0-9\-]{0,64}$`)
	roleARNPattern = regexp.MustCompile(`^arn:aws[a-z\-]*:iam::\d{12}:role/[A-Za-z0-9+=,.@_\-/]{1,512}$`)
)

// Validate checks a customer connection's own fields: names, the
// provider's required settings, prefixes and the auth method. The
// endpoint's network policy is checked separately.
func (c StorageConnection) Validate() error {
	fail := func(msg string) error { return fmt.Errorf("%w: %s", ErrInvalidConnection, msg) }
	name := strings.TrimSpace(c.Name)
	if name == "" || len(name) > 128 || strings.ContainsFunc(name, func(r rune) bool { return r < ' ' }) {
		return fail("name must be 1-128 printable characters")
	}
	if !slices.Contains(CustomerProviders, c.Provider) {
		return fail("provider must be one of AWS_S3, S3_COMPATIBLE, CLOUDFLARE_R2, GOOGLE_CLOUD_STORAGE, AZURE_BLOB")
	}
	if !slices.Contains(authMethods[c.Provider], c.AuthMethod) {
		return fail(fmt.Sprintf("%s accepts auth methods %v", c.Provider, authMethods[c.Provider]))
	}
	if !bucketPattern.MatchString(c.Bucket) || strings.Contains(c.Bucket, "..") {
		return fail("bucket (or container) must be 3-222 characters of a-z, 0-9, '.', '-' and '_'")
	}
	if !regionPattern.MatchString(c.Region) || !accountPattern.MatchString(c.AccountID) {
		return fail("region and account_id must be plain identifiers")
	}
	if !prefixPattern.MatchString(c.StagingPrefix) || !prefixPattern.MatchString(c.ReadyPrefix) || c.StagingPrefix == c.ReadyPrefix {
		return fail("staging_prefix and ready_prefix must differ, each 1-63 characters of a-z, 0-9, '-' and '_'")
	}
	if c.StagingMode != StagingInPlace && c.StagingMode != StagingPlatform {
		return fail("staging_mode must be CONNECTION or PLATFORM")
	}
	if c.AuthMethod == AuthSASToken && c.StagingMode != StagingPlatform {
		return fail("a SAS token cannot sign client uploads: use staging_mode PLATFORM")
	}
	switch c.Provider {
	case ProviderAWSS3:
		if c.Region == "" {
			return fail("AWS_S3 needs a region")
		}
		if c.AuthMethod == AuthAssumeRole && !roleARNPattern.MatchString(c.RoleARN) {
			return fail("ASSUME_ROLE needs a role_arn (arn:aws:iam::<account>:role/<name>)")
		}
	case ProviderS3Compatible:
		if c.Endpoint == "" {
			return fail("S3_COMPATIBLE needs an endpoint")
		}
	case ProviderR2, ProviderAzureBlob:
		if c.AccountID == "" {
			return fail(string(c.Provider) + " needs account_id")
		}
	}
	if c.AuthMethod != AuthAssumeRole && c.RoleARN != "" {
		return fail("role_arn is for ASSUME_ROLE")
	}
	return nil
}
